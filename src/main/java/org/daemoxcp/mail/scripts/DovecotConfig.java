    private static String config24() {
        StringBuilder sb = new StringBuilder();
        sb.append("""
            echo "[CONFIG] Writing the configuration in Dovecot 2.4 format"
            echo "[CONFIG] Checked on a real Dovecot 2.4.5; doveconf decides all the same, and if it refuses"
            echo "[CONFIG] the previous configuration goes back in place without restarts."
            """);
        for (FileConf f : file24()) {
            String delim = "DOVECOT_" + f.path().replaceAll("[^A-Za-z0-9]", "_").toUpperCase();
            // Quoted heredoc when there are NO variables to expand: this way a $ in the
            // content (the %{...} have none, but the queries might) stays literal.
            // A file in a subfolder (sieve/): the folder first, conf.d already exists.
            int slash = f.path().lastIndexOf('/');
            if (slash > 0 && !f.path().startsWith("conf.d/"))
                sb.append("\nmkdir -p \"$DOVECOT_ETC/").append(f.path(), 0, slash).append("\"");
            sb.append("\ncat > \"$DOVECOT_ETC/").append(f.path()).append("\" <<")
              .append(f.expand() ? delim : "'" + delim + "'").append("\n");
            sb.append(f.content());
            sb.append(delim).append("\n");
        }
        sb.append("""

            # In 2.4 dovecot-sql.conf no longer exists: if it is left over from a 2.3 it is moved
            # out of the way, otherwise a file with the database password would stay on disk
            # that nobody reads or updates any more.
            if [ -f "$DOVECOT_ETC/dovecot-sql.conf" ]; then
                mv "$DOVECOT_ETC/dovecot-sql.conf" "$DOVECOT_ETC/dovecot-sql.conf.pre-2.4"
                chmod 600 "$DOVECOT_ETC/dovecot-sql.conf.pre-2.4"
            fi
            """);
        return sb.toString();
    }
