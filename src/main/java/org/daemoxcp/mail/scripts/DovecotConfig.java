    /** The quota file in 2.4 (conf.d), written by the installation and by the repair at boot (DovecotQuota). */
    public static final String QUOTA_FILE_NAME = "90-quota.conf";

    /**
     * The mailbox quotas in 2.4: the quota plugin for all the protocols (LMTP included: the mail_plugins entries
     * inside protocol are added to these), imap_quota for IMAP (GETQUOTAROOT, which Roundcube shows), a root
     * with the count driver, and the quota-status service that Postfix queries before accepting a recipient.
     *
     * <p>The limit of each mailbox is given by the sql userdb ({@link #QUOTA_USERDB}); without it, quota_storage_size
     * applies, that is, no limit. A full mailbox answers 452 4.2.2: temporary, the sender retries for a few days and
     * the message arrives if space is freed in the meantime, instead of bouncing. For a recipient that is not a
     * mailbox, or when everything is fine, DUNNO: Postfix's other rules decide, as before. The socket is in
     * Postfix's queue, 0600 owned by Postfix, like the LMTP one. The service runs as vmail, not root: the first test
     * on the VM ran it as root, and ServiceUsers reported it (2026-11-18).
     */
    public static final String QUOTA_FILE = """
            # The mailbox quotas (DaemoxCP Mail). Each mailbox's limit comes from the database (userdb sql in
            # auth-sql.conf.ext, quota_mb in MB; 0 = no limit).
            mail_plugins {
              quota = yes
            }

            protocol imap {
              mail_plugins {
                imap_quota = yes
              }
            }

            quota "User quota" {
            }

            # Postfix asks before accepting a recipient (check_policy_service). A full mailbox: 452,
            # temporary, the sender retries for a few days. It runs as vmail: it reads the userdb (auth-userdb belongs to
            # vmail) and the mailbox indexes (vmail's); it does not need root (ServiceUsers would report it).
            service quota-status {
              executable = quota-status -p postfix
              user = vmail
              unix_listener /var/spool/postfix/private/quota-status {
                mode = 0600
                user = postfix
                group = postfix
              }
              client_limit = 1
            }

            quota_status_success = DUNNO
            quota_status_nouser = DUNNO
            quota_status_overquota = 452 4.2.2 Mailbox is full
            """;

    /**
     * The limit of each mailbox, before the static userdb: its fields are added to those of static (continue-ok), and
     * an address that is not an active mailbox passes to static as before (continue). A query that fails also passes
     * to static (result_internalfail = continue): it is already 2.4's behaviour, written down so as not to depend on
     * it. Measured on the VM on 2026-11-18, with a jar without quotas that had removed quota_mb from Dovecot's MySQL
     * user (MailDbUsers): a real mailbox still receives, without its limit, with the line and also without it; only
     * an address that does not exist answers "internal error" instead of "unknown". iterate_query is needed by
     * doveadm with -A (the "Mailboxes" page).
     */
    public static final String QUOTA_USERDB = """
            # Each mailbox's limit (quota_mb in MB; 0 = no limit): it adds to the fields of userdb static.
            # If the query fails it goes on without a quota (already so in 2.4, written for clarity).
            # And after how many days Dovecot empties Junk and Trash by itself (junk_expunge_days, trash_expunge_days;
            # 0 = never: the field stays NULL, Dovecot does not get it and empties nothing).
            userdb sql {
              query = SELECT CONCAT(quota_mb, 'M') AS quota_storage_size, IF(junk_expunge_days > 0, CONCAT(junk_expunge_days, 'd'), NULL) AS 'namespace/inbox/mailbox/Junk/mailbox_autoexpunge', IF(trash_expunge_days > 0, CONCAT(trash_expunge_days, 'd'), NULL) AS 'namespace/inbox/mailbox/Trash/mailbox_autoexpunge' FROM mailboxes WHERE email = '%{user}' AND active = 1
              iterate_query = SELECT email AS user FROM mailboxes WHERE active = 1
              result_success = continue-ok
              result_failure = continue
              result_internalfail = continue
            }

            """;

