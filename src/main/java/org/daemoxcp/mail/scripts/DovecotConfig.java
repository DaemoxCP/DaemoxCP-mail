    /** Il file delle quote nella 2.4 (conf.d), scritto dall'installazione e dalla riparazione all'avvio (DovecotQuota). */
    public static final String QUOTA_FILE_NAME = "90-quota.conf";

    /**
     * Le quote delle caselle nella 2.4: il plugin quota per tutti i protocolli (LMTP compreso: le voci di mail_plugins
     * dentro protocol si aggiungono a queste), imap_quota per IMAP (GETQUOTAROOT, che Roundcube mostra), una radice
     * col driver count, e il servizio quota-status che Postfix interroga prima di accettare un destinatario.
     *
     * <p>Il limite di ogni casella lo da' il userdb sql ({@link #QUOTA_USERDB}); senza, vale quota_storage_size, cioe'
     * nessun limite. Una casella piena risponde 452 4.2.2: temporaneo, chi manda riprova per qualche giorno e il
     * messaggio arriva se intanto si fa spazio, invece di tornare indietro. Per un destinatario che non e' una
     * casella, o quando tutto va bene, DUNNO: decidono le altre regole di Postfix, come prima. Il socket sta nella
     * coda di Postfix, 0600 suo, come quello di LMTP. Il servizio gira come vmail, non root: la prima prova sulla VM
     * l'ha fatto girare da root, e ServiceUsers l'ha segnalato (18/11/2026).
     */
    public static final String QUOTA_FILE = """
            # The mailbox quotas (DaemoxCP Mail). Each mailbox's limit comes from the database (userdb sql in
            # auth-sql.conf.ext, quota_mb in MB; 0 = no limit).
            mail_plugins {
              quota = yes
            }

            protocol imap {
              mail_plugins {
                imap_quota = yes
              }
            }

            quota "User quota" {
            }

            # Postfix asks before accepting a recipient (check_policy_service). A full mailbox: 452,
            # temporary, the sender retries for a few days. It runs as vmail: it reads the userdb (auth-userdb belongs to
            # vmail) and the mailbox indexes (vmail's); it does not need root (ServiceUsers would report it).
            service quota-status {
              executable = quota-status -p postfix
              user = vmail
              unix_listener /var/spool/postfix/private/quota-status {
                mode = 0600
                user = postfix
                group = postfix
              }
              client_limit = 1
            }

            quota_status_success = DUNNO
            quota_status_nouser = DUNNO
            quota_status_overquota = 452 4.2.2 Mailbox is full
            """;

    /**
     * Il limite di ogni casella, prima del userdb static: i suoi campi si aggiungono a quelli di static (continue-ok), e
     * un indirizzo che non e' una casella attiva passa a static come prima (continue). Una domanda che fallisce passa
     * anch'essa a static (result_internalfail = continue): e' gia' il comportamento della 2.4, scritto per non
     * dipenderne. Misurato sulla VM il 18/11/2026, con un jar senza le quote che aveva tolto quota_mb all'utente MySQL
     * di Dovecot (MailDbUsers): una casella vera riceve ancora, senza il suo limite, con la riga e anche senza; solo un
     * indirizzo che non esiste risponde «errore interno» invece di «sconosciuto». iterate_query serve a doveadm con -A
     * (la pagina Caselle).
     */
    public static final String QUOTA_USERDB = """
            # Each mailbox's limit (quota_mb in MB; 0 = no limit): it adds to the fields of userdb static.
            # If the query fails it goes on without a quota (already so in 2.4, written for clarity).
            # And after how many days Dovecot empties Junk and Trash by itself (junk_expunge_days, trash_expunge_days;
            # 0 = never: the field stays NULL, Dovecot does not get it and empties nothing).
            userdb sql {
              query = SELECT CONCAT(quota_mb, 'M') AS quota_storage_size, IF(junk_expunge_days > 0, CONCAT(junk_expunge_days, 'd'), NULL) AS 'namespace/inbox/mailbox/Junk/mailbox_autoexpunge', IF(trash_expunge_days > 0, CONCAT(trash_expunge_days, 'd'), NULL) AS 'namespace/inbox/mailbox/Trash/mailbox_autoexpunge' FROM mailboxes WHERE email = '%{user}' AND active = 1
              iterate_query = SELECT email AS user FROM mailboxes WHERE active = 1
              result_success = continue-ok
              result_failure = continue
              result_internalfail = continue
            }

            """;

