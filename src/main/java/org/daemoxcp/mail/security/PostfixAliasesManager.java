package org.daemoxcp.mail.security;

import java.io.BufferedReader;
import org.daemoxcp.mail.i18n.I18n;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.logging.Logger;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Management and auto-fix of Postfix's system alias map.
 *
 * Postfix keeps an "alias map" used to forward mail addressed to local system
 * accounts (root, postmaster, mailer-daemon, etc.). The path is configured in
 * {@code main.cf} via {@code alias_database} (usually {@code /etc/aliases} on Linux
 * or {@code /etc/mail/aliases} on FreeBSD). Postfix reads a binary file {@code <path>.db}
 * compiled with {@code postalias <path>}.
 *
 * Typical error in the logs if the .db is missing:
 * {@code postfix/smtpd: error: open database /etc/aliases.db: No such file or directory}
 *
 * This manager:
 *  - Diagnoses: reads {@code alias_database} via {@code postconf -h}, checks that the
 *    sources and the .db exist.
 *  - Fixes: creates the source if missing with safe defaults + compiles the .db with postalias.
 *  - Sets root's forward: updates/adds the {@code root: <email>} line without destroying the file.
 *  - Reloads Postfix with {@code service postfix reload}.
 *
 * All methods are best-effort and safe: on error they log and return a
 * structured result without propagating exceptions to the web server.
 */
public class PostfixAliasesManager {
    private static final Logger LOGGER = Logger.getLogger(PostfixAliasesManager.class.getName());

    private static final String POSTCONF = "/usr/local/sbin/postconf";
    private static final String POSTALIAS = "/usr/local/sbin/postalias";
    private static final String SERVICE = "/usr/sbin/service";

    /**
     * Safe defaults for the aliases file. They are used only if the source file
     * does not exist: we write a minimal standard content. Root forwards to itself
     * (the user can change it from the UI with {@link #setRootForward(String)}).
     */
    private static final String DEFAULT_ALIASES =
        "# /etc/aliases — system mail aliases for Postfix\n" +
        "# Auto-generated by DaemoxCP Mail.\n" +
        "# After every change run: postalias <file>\n" +
        "# or use the \"Fix\" button in the panel.\n" +
        "\n" +
        "postmaster:    root\n" +
        "mailer-daemon: root\n" +
        "nobody:        root\n" +
        "abuse:         root\n" +
        "hostmaster:    root\n" +
        "webmaster:     root\n" +
        "www:           root\n" +
        "ftp:           root\n" +
        "root:          root\n";

    // ========== STATUS ==========

    public AliasesStatus diagnose() {
        AliasesStatus s = new AliasesStatus();
        try {
            String aliasDatabase = readPostconfHash("alias_database");
            String aliasMaps     = readPostconfHash("alias_maps");
            s.aliasDatabaseRaw = aliasDatabase;
            s.aliasMapsRaw     = aliasMaps;

            // Extract the first file path from `alias_database` (format: hash:/path[,hash:/path2,...])
            String primary = parseFirstHashPath(aliasDatabase);
            if (primary == null) {
                // Fallback: prova /etc/aliases (Linux default) o /etc/mail/aliases (FreeBSD)
                primary = "/etc/aliases";
            }
            s.aliasFile = primary;
            s.aliasDbFile = primary + ".db";

            Path src = Paths.get(s.aliasFile);
            Path db  = Paths.get(s.aliasDbFile);
            s.sourceExists = Files.exists(src);
            s.dbExists     = Files.exists(db);

            // Compute "stale": .db older than the source
            if (s.sourceExists && s.dbExists) {
                try {
                    long srcM = Files.getLastModifiedTime(src).toMillis();
                    long dbM  = Files.getLastModifiedTime(db).toMillis();
                    s.dbStaleVsSource = (dbM < srcM);
                } catch (Exception ignore) {}
            }

            // Extract the current root forward (if the source exists)
            if (s.sourceExists) {
                s.rootForward = extractRootForward(src);
                try { s.sourceContent = Files.readString(src, StandardCharsets.UTF_8); }
                catch (Exception ignore) {}
            }

            // Verdict
            if (!s.sourceExists) {
                s.overall = "MISSING_SOURCE";
                s.summary = I18n.tr("server.aliases.missingSource", java.util.Map.of("file", String.valueOf(s.aliasFile)));
            } else if (!s.dbExists) {
                s.overall = "MISSING_DB";
                s.summary = I18n.tr("server.aliases.missingDb", java.util.Map.of("file", String.valueOf(s.aliasFile), "db", String.valueOf(s.aliasDbFile)));
            } else if (s.dbStaleVsSource) {
                s.overall = "STALE_DB";
                s.summary = I18n.tr("server.aliases.staleDb", java.util.Map.of("db", String.valueOf(s.aliasDbFile)));
            } else {
                s.overall = "OK";
                s.summary = I18n.tr("server.aliases.ok", java.util.Map.of("file", String.valueOf(s.aliasFile), "db", String.valueOf(s.aliasDbFile)));
            }

            s.success = true;
            return s;
        } catch (Exception e) {
            s.success = false;
            s.error = I18n.tr("server.aliases.diagError", java.util.Map.of("err", org.daemoxcp.mail.util.ErrorText.detail("PostfixAliasesManager", e)));
            s.overall = "ERROR";
            return s;
        }
    }

    // ========== FIX ==========

    /**
     * Runs the auto-fix:
     *  1. If the source is missing -> creates it with safe defaults.
     *  2. Runs postalias to (re)compile the .db.
     *  3. Reloads Postfix.
     * All the steps are accumulated in the log.
     */
    public FixResult fix() {
        FixResult r = new FixResult();
        try {
            AliasesStatus s = diagnose();
            if (!s.success) {
                r.success = false;
                r.message = s.error;
                return r;
            }
            r.aliasFile = s.aliasFile;
            r.aliasDbFile = s.aliasDbFile;

            // 1) Create the source if missing
            if (!s.sourceExists) {
                Path src = Paths.get(s.aliasFile);
                try {
                    if (src.getParent() != null && !Files.exists(src.getParent())) {
                        Files.createDirectories(src.getParent());
                    }
                    Files.writeString(src, DEFAULT_ALIASES, StandardCharsets.UTF_8,
                        StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
                    r.log.append("✓ ").append(I18n.tr("server.aliases.created", java.util.Map.of("file", String.valueOf(s.aliasFile)))).append("\n");
                    s.sourceExists = true;
                } catch (Exception e) {
                    r.success = false;
                    r.message = I18n.tr("server.aliases.createError", java.util.Map.of("file", String.valueOf(s.aliasFile), "err", org.daemoxcp.mail.util.ErrorText.detail("PostfixAliasesManager", e)));
                    return r;
                }
            } else {
                r.log.append("✓ ").append(I18n.tr("server.aliases.sourcePresent", java.util.Map.of("file", String.valueOf(s.aliasFile)))).append("\n");
            }

            // 2) postalias <file>
            CommandResult pc = runCommand(POSTALIAS, s.aliasFile);
            if (pc.exitCode == 0) {
                r.log.append("✓ postalias ").append(s.aliasFile).append(" — OK\n");
            } else {
                r.log.append("✗ postalias ").append(s.aliasFile)
                    .append(" exit=").append(pc.exitCode)
                    .append(" output: ").append(pc.output).append("\n");
                r.success = false;
                r.message = I18n.tr("server.aliases.postaliasExit", java.util.Map.of("c", String.valueOf(pc.exitCode), "out", String.valueOf(pc.output)));
                return r;
            }

            // 3) service postfix reload
            CommandResult sr = runCommand(SERVICE, "postfix", "reload");
            if (sr.exitCode == 0) {
                r.log.append("✓ ").append(I18n.tr("server.aliases.reloaded")).append("\n");
            } else {
                // We do not block: the .db file is already updated even without a reload
                // because Postfix rereads it automatically at the next lookup.
                r.log.append("⚠ ").append(I18n.tr("server.aliases.reloadNonBlocking", java.util.Map.of("c", String.valueOf(sr.exitCode), "out", String.valueOf(sr.output)))).append("\n");
            }

            r.success = true;
            r.message = I18n.tr("server.aliases.restored", java.util.Map.of("file", String.valueOf(s.aliasFile), "db", String.valueOf(s.aliasDbFile)));
            return r;
        } catch (Exception e) {
            r.success = false;
            r.message = I18n.tr("server.aliases.fixError", java.util.Map.of("err", org.daemoxcp.mail.util.ErrorText.detail("PostfixAliasesManager", e)));
            return r;
        }
    }

    /**
     * Updates root's forwarding to a specific address (or sets it back to self).
     * Changes/adds the {@code root: <forwardTo>} line in the source file
     * keeping everything else.
     * After the update it runs postalias + reload.
     *
     * @param forwardTo email (e.g. "owner@domain-a.test") or null to set it back to "root"
     */
    public FixResult setRootForward(String forwardTo) {
        FixResult r = new FixResult();
        try {
            if (forwardTo == null) forwardTo = "root";
            forwardTo = forwardTo.trim();
            if (forwardTo.isEmpty()) forwardTo = "root";

            // Very basic validation (email or local username)
            if (!forwardTo.matches("^[a-zA-Z0-9._+\\-@]+$")) {
                r.success = false;
                r.message = I18n.tr("server.aliases.badForward");
                return r;
            }

            AliasesStatus s = diagnose();
            if (!s.sourceExists) {
                // If it does not exist, create it first with the defaults, then apply the forward
                FixResult init = fix();
                if (!init.success) return init;
                s = diagnose();
            }
            r.aliasFile = s.aliasFile;
            r.aliasDbFile = s.aliasDbFile;

            Path src = Paths.get(s.aliasFile);
            String content = Files.readString(src, StandardCharsets.UTF_8);

            // Pattern: find the "root:" line (possibly with whitespace) and replace it.
            // If it is not there, append it.
            Pattern p = Pattern.compile("(?m)^[ \\t]*root[ \\t]*:.*$");
            Matcher m = p.matcher(content);
            String newLine = "root:          " + forwardTo;
            String newContent;
            if (m.find()) {
                newContent = m.replaceFirst(Matcher.quoteReplacement(newLine));
                r.log.append("✓ ").append(I18n.tr("server.aliases.rootChanged", java.util.Map.of("file", String.valueOf(s.aliasFile)))).append("\n");
            } else {
                if (!content.endsWith("\n")) content = content + "\n";
                newContent = content + newLine + "\n";
                r.log.append("✓ ").append(I18n.tr("server.aliases.rootAdded", java.util.Map.of("file", String.valueOf(s.aliasFile)))).append("\n");
            }

            Files.writeString(src, newContent, StandardCharsets.UTF_8,
                StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.WRITE);

            // Recompile + reload
            CommandResult pc = runCommand(POSTALIAS, s.aliasFile);
            if (pc.exitCode == 0) {
                r.log.append("✓ postalias ").append(s.aliasFile).append(" — OK\n");
            } else {
                r.log.append("✗ postalias exit=").append(pc.exitCode).append(" ").append(pc.output).append("\n");
                r.success = false;
                r.message = I18n.tr("server.aliases.postaliasFailed", java.util.Map.of("out", String.valueOf(pc.output)));
                return r;
            }
            CommandResult sr = runCommand(SERVICE, "postfix", "reload");
            if (sr.exitCode == 0) r.log.append("✓ ").append(I18n.tr("server.aliases.reloaded")).append("\n");
            else r.log.append("⚠ ").append(I18n.tr("server.aliases.reloadExit", java.util.Map.of("c", String.valueOf(sr.exitCode)))).append("\n");

            r.success = true;
            r.message = I18n.tr("server.aliases.rootSet", java.util.Map.of("to", String.valueOf(forwardTo)));
            return r;
        } catch (Exception e) {
            r.success = false;
            r.message = I18n.tr("server.aliases.error", java.util.Map.of("err", org.daemoxcp.mail.util.ErrorText.detail("PostfixAliasesManager", e)));
            return r;
        }
    }

    /**
     * Non-destructive auto-setup to call at panel boot.
     * If the diagnosis finds problems, it applies the fix automatically.
     * If everything is OK, it does nothing. Idempotent.
     */
    public void ensureAtBoot() {
        // At startup there is no request: summaries and messages end up only in the log, in English.
        I18n.setCurrent("en");
        try {
            AliasesStatus s = diagnose();
            if (!s.success) {
                LOGGER.warning("[PostfixAliases] Diagnose failed at boot: " + s.error);
                return;
            }
            if ("OK".equals(s.overall)) {
                LOGGER.info("[PostfixAliases] " + s.summary);
                return;
            }
            LOGGER.warning("[PostfixAliases] " + s.overall + " — " + s.summary + " — applying the automatic fix.");
            FixResult fr = fix();
            if (fr.success) LOGGER.info("[PostfixAliases] Auto-fix OK: " + fr.message);
            else LOGGER.warning("[PostfixAliases] Auto-fix FAILED: " + fr.message);
        } catch (Throwable t) {
            LOGGER.warning("[PostfixAliases] ensureAtBoot exception: " + t.getMessage());
        } finally {
            I18n.clearCurrent();
        }
    }

    // ========== HELPERS ==========

    private String readPostconfHash(String key) {
        try {
            CommandResult r = runCommand(POSTCONF, "-h", key);
            if (r.exitCode == 0) return r.output.trim();
        } catch (Exception ignore) {}
        return null;
    }

    /** Da "hash:/etc/aliases, hash:/etc/mail/aliases" → "/etc/aliases". */
    private String parseFirstHashPath(String postconfValue) {
        if (postconfValue == null) return null;
        for (String part : postconfValue.split("[,\\s]+")) {
            part = part.trim();
            int idx = part.indexOf(':');
            if (idx > 0 && idx + 1 < part.length()) {
                String type = part.substring(0, idx);
                String path = part.substring(idx + 1);
                if ("hash".equalsIgnoreCase(type) || "btree".equalsIgnoreCase(type) || "lmdb".equalsIgnoreCase(type)) {
                    if (path.startsWith("/")) return path;
                }
            }
        }
        return null;
    }

    private String extractRootForward(Path source) {
        try {
            for (String line : Files.readAllLines(source, StandardCharsets.UTF_8)) {
                String trimmed = line.trim();
                if (trimmed.startsWith("#") || trimmed.isEmpty()) continue;
                if (trimmed.toLowerCase().startsWith("root:") || trimmed.toLowerCase().startsWith("root :")) {
                    int colon = trimmed.indexOf(':');
                    return trimmed.substring(colon + 1).trim();
                }
            }
        } catch (Exception ignore) {}
        return null;
    }

    private CommandResult runCommand(String... cmd) {
        CommandResult r = new CommandResult();
        try {
            // TODO: migrate to Shell.run when touched
            ProcessBuilder pb = new ProcessBuilder(cmd);
            org.daemoxcp.mail.util.Shell.applyPath(pb);
            pb.redirectErrorStream(true);
            Process p = pb.start();
            StringBuilder sb = new StringBuilder();
            try (BufferedReader br = new BufferedReader(new InputStreamReader(p.getInputStream(), StandardCharsets.UTF_8))) {
                String line;
                while ((line = br.readLine()) != null) sb.append(line).append('\n');
            }
            boolean done = p.waitFor(10, TimeUnit.SECONDS);
            if (!done) {
                p.destroyForcibly();
                r.exitCode = -1;
                r.output = sb + "\n[timeout after 10s]";
                return r;
            }
            r.exitCode = p.exitValue();
            r.output = sb.toString().trim();
        } catch (Exception e) {
            r.exitCode = -2;
            r.output = "exception: " + e.getMessage();
        }
        return r;
    }

    private static class CommandResult {
        int exitCode;
        String output = "";
    }

    // ========== RESULT CLASSES ==========

    public static class AliasesStatus {
        public boolean success;
        public String error;
        public String overall;          // OK / MISSING_SOURCE / MISSING_DB / STALE_DB / ERROR
        public String summary;
        public String aliasFile;        // es. /etc/aliases
        public String aliasDbFile;      // es. /etc/aliases.db
        public String aliasMapsRaw;     // raw value from postconf -h alias_maps
        public String aliasDatabaseRaw; // raw value from postconf -h alias_database
        public boolean sourceExists;
        public boolean dbExists;
        public boolean dbStaleVsSource;
        public String rootForward;      // where root is forwarded to (may be null)
        public String sourceContent;    // full content of the file (for UI / audit)
    }

    public static class FixResult {
        public boolean success;
        public String message;
        public String aliasFile;
        public String aliasDbFile;
        public StringBuilder log = new StringBuilder();
    }
}
