package org.daemoxcp.mail.security;

import org.daemoxcp.mail.util.Shell;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.PosixFilePermissions;
import java.time.Duration;
import java.util.List;
import java.util.Set;
import java.util.SortedSet;
import java.util.TreeSet;
import java.util.logging.Logger;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * pf fa entrare solo quello che serve (deciso dal committente l'08/11/2026).
 *
 * <p>Il pf.conf che il pannello scriveva era «minimo»: un {@code pass} che faceva entrare tutto, e
 * bloccati solo gli indirizzi di fail2ban, della tabella permaban e delle regole del pannello (paesi,
 * liste). Ogni porta aperta per sbaglio, o da un servizio che nessuno usa, era raggiungibile da
 * chiunque: sul server vero ManageSieve (4190) e ntpd come server (123/udp), che nessuno usa da fuori.
 *
 * <p>Adesso in ingresso passa solo l'elenco qui sotto, il resto si scarta; in uscita passa tutto:
 * <ul>
 *   <li>SSH: le porte su cui sshd ascolta adesso, e comunque la 22, aperte a tutti come prima. SSH non
 *       si tocca: la sua regola fa entrare quello che entrava, e i blocchi che lo riguardavano
 *       (fail2ban, permaban, le liste del pannello) restano quelli;</li>
 *   <li>la posta: 25, 465, 587, 143, 993. Per le porte dei client le regole dei paesi del pannello
 *       (anchor panel-fw) vengono prima e decidono loro, come prima;</li>
 *   <li>il web: 80 (la sfida HTTP dei certificati, AcmeUser) e 443 (MTA-STS, autoconfig), la webmail
 *       e il pannello sulle loro porte;</li>
 *   <li>quello senza cui la macchina perde la rete: ICMP essenziale, ICMPv6 (vicini e router di IPv6),
 *       le risposte DHCP (il server vero prende l'indirizzo IPv4 con DHCP).</li>
 * </ul>
 * POP3 (110, 995) entra solo se l'amministratore l'ha acceso nelle Impostazioni (Pop3). Chiusi, fra
 * quelli che ascoltavano sul server vero: POP3 (spento finche' non si sceglie), ManageSieve da fuori
 * (Roundcube lo usa dalla macchina stessa, e il loopback non si filtra), ntpd come server.
 *
 * <p>Si trasforma solo un pf.conf del pannello, riconosciuto dalla prima riga e fatto solo di righe
 * che il pannello scrive. Uno con regole d'altri resta com'e', e il registro lo dice. Prima di caricare:
 * una copia, la prova di sintassi; dopo: le regole nel kernel si controllano, e se SSH non risulta
 * aperto si torna alla copia.
 */
public final class PfPolicy {

    private static final Logger LOGGER = Logger.getLogger(PfPolicy.class.getName());

    static final String PF_CONF = "/etc/pf.conf";
    static final String PFCTL = "/sbin/pfctl";

    /** La prima riga del pf.conf scritto da qui. */
    static final String HEADER = "# /etc/pf.conf, scritto dal pannello mail: entra solo quello che serve.";
    /** Le prime righe dei pf.conf che il pannello scriveva prima (l'installazione, il pulsante della pagina). */
    static final List<String> OLD_HEADERS = List.of(
            "# /etc/pf.conf, scritto dall'installazione del pannello mail.",
            "# /etc/pf.conf — generato automaticamente dal mail panel",
            "# /etc/pf.conf, generated by the mail panel");

    /** Le regole che il pannello scriveva nel pf.conf (installazione, Fail2banAutoSetup, PfFirewallManager). */
    static final Set<String> PANEL_RULES = panelRules();

    /** Le regole del pannello, con la lista dei ban permanenti dove sta adesso e dove stava prima ("dataFolders"). */
    private static Set<String> panelRules() {
        java.util.Set<String> r = new java.util.LinkedHashSet<>(List.of("set skip on lo", "anchor \"f2b/*\"", "pass",
                "block in quick from <permaban>", "anchor \"panel-fw\"",
                "table <permaban> persist file \"/var/db/daemoxcp-mail/permaban.list\""));
        for (String[] p : org.daemoxcp.mail.system.LegacyNames.pairs("dataFolders"))
            r.add("table <permaban> persist file \"" + p[0] + "/permaban.list\"");
        return Set.copyOf(r);
    }
    private static final Pattern TABLE_LIMIT = Pattern.compile("set\\s+limit\\s+table-entries\\s+(\\d{1,10})");
    /** Le regole che scrive questa classe: in un file col suo HEADER si riconoscono e si riscrivono. */
    private static final List<String> POLICY_PREFIXES = List.of("block in all", "pass out all keep state",
            "pass in inet proto icmp ", "pass in inet6 proto icmp6", "pass in inet proto udp from port 67 to port 68",
            "pass in proto tcp to port {");

    /** La posta e il web: sempre. */
    static final SortedSet<Integer> FIXED = new TreeSet<>(List.of(25, 80, 143, 443, 465, 587, 993));

    private PfPolicy() {}

    /** Le porte TCP che entrano: quelle di sshd (con la 22) a parte, le altre insieme. */
    record Ports(SortedSet<Integer> ssh, SortedSet<Integer> services) {
        Ports {
            ssh = new TreeSet<>(ssh);
            ssh.add(22);
            services = new TreeSet<>(services);
            services.addAll(FIXED);
            services.removeAll(ssh);
        }
    }

    private static String list(SortedSet<Integer> ports) {
        StringBuilder b = new StringBuilder("{ ");
        for (int p : ports) b.append(b.length() > 2 ? ", " : "").append(p);
        return b.append(" }").toString();
    }

    /** Il pf.conf del pannello. tableLimit: il valore di «set limit table-entries» da tenere, o null. */
    static String render(Ports p, String tableLimit) {
        StringBuilder b = new StringBuilder();
        b.append(HEADER).append('\n');
        b.append("#\n");
        b.append("# In ingresso passa solo l'elenco in fondo, il resto si scarta; in uscita passa tutto.\n");
        b.append("# Prima dell'elenco i blocchi: fail2ban, la tabella permaban, le regole del pannello (paesi,\n");
        b.append("# liste), che decidono subito (quick). Lo riscrive il pannello a ogni avvio dalla sua\n");
        b.append("# configurazione (PfPolicy); se ci aggiungi regole tue, non lo tocca piu' e lo dice nel registro.\n\n");
        if (tableLimit != null) b.append("# Le tabelle dei paesi sono grandi.\nset limit table-entries ").append(tableLimit).append("\n\n");
        b.append("# Il loopback non si filtra.\nset skip on lo\n\n");
        b.append("# I blocchi di fail2ban (block in quick, dall'azione pf delle sue jail).\nanchor \"f2b/*\"\n\n");
        b.append("# I blocchi permanenti del pannello.\n");
        b.append("table <permaban> persist file \"/var/db/daemoxcp-mail/permaban.list\"\nblock in quick from <permaban>\n\n");
        b.append("# Le regole del pannello: liste di indirizzi e paesi (PfFirewallManager).\nanchor \"panel-fw\"\n\n");
        b.append("# Il resto: in ingresso solo quello che serve.\n");
        b.append("block in all\n");
        b.append("pass out all keep state\n\n");
        b.append("# Senza questi la macchina perde la rete: ICMP essenziale, IPv6 (vicini, router), le risposte DHCP.\n");
        b.append("pass in inet proto icmp icmp-type { echoreq, unreach, timex, paramprob }\n");
        b.append("pass in inet6 proto icmp6\n");
        b.append("pass in inet proto udp from port 67 to port 68\n\n");
        b.append("# SSH: le porte di sshd, aperte a tutti come prima.\n");
        b.append("pass in proto tcp to port ").append(list(p.ssh())).append(" keep state\n\n");
        b.append("# Posta, web (sfida HTTP dei certificati, MTA-STS), webmail, pannello.\n");
        b.append("pass in proto tcp to port ").append(list(p.services())).append(" keep state\n");
        return b.toString();
    }

    /**
     * Il pf.conf nuovo, o null se questo non e' un pf.conf del pannello: la prima riga e' un'altra, o
     * c'e' una regola che il pannello non scrive. Gli altri commenti non contano (si riscrivono).
     */
    static String transform(String current, Ports p) {
        if (current == null) return null;
        String first = current.lines().filter(l -> !l.isBlank()).findFirst().orElse("").trim();
        boolean ours = first.equals(HEADER);
        if (!ours && !OLD_HEADERS.contains(first)) return null;
        String tableLimit = null;
        for (String line : current.split("\n")) {
            String t = line.trim().replaceAll("\\s+", " ");
            if (t.isEmpty() || t.startsWith("#")) continue;
            Matcher m = TABLE_LIMIT.matcher(t);
            if (m.matches()) {
                tableLimit = m.group(1);
                continue;
            }
            if (PANEL_RULES.contains(t)) continue;
            if (ours && POLICY_PREFIXES.stream().anyMatch(t::startsWith)) continue;
            return null;
        }
        return render(p, tableLimit);
    }

    /** Il pf.conf del pannello con le porte di adesso (il pulsante che crea un pf.conf che manca). */
    public static String renderNow() {
        return render(currentPorts(), null);
    }

    /** Le porte TCP su cui sshd ascolta adesso, dall'uscita di sockstat -46l -P tcp. */
    static SortedSet<Integer> sshPorts(String sockstat) {
        SortedSet<Integer> out = new TreeSet<>();
        if (sockstat == null) return out;
        for (String line : sockstat.split("\n")) {
            String[] f = line.trim().split("\\s+");
            if (f.length < 6 || !f[1].equals("sshd")) continue;
            String local = f[5];
            int colon = local.lastIndexOf(':');
            if (colon < 0) continue;
            try {
                int port = Integer.parseInt(local.substring(colon + 1));
                if (port > 0 && port < 65536) out.add(port);
            } catch (NumberFormatException ignored) {
                // non e' una porta
            }
        }
        return out;
    }

    /** Le porte di adesso: sshd da sockstat, il pannello e la webmail dalla configurazione, POP3 se e' acceso. */
    static Ports currentPorts() {
        SortedSet<Integer> ssh = sshPorts(Shell.run(Duration.ofSeconds(15), "sockstat", "-46l", "-P", "tcp").output());
        SortedSet<Integer> services = new TreeSet<>();
        addPort(services, configValue("mail_panel_port"));
        if (org.daemoxcp.mail.Main.dbManager != null) addPort(services, org.daemoxcp.mail.Main.dbManager.getRoundcubePort());
        if (org.daemoxcp.mail.system.Pop3.wanted()) services.addAll(List.of(110, 995));
        return new Ports(ssh, services);
    }

    private static String configValue(String column) {
        if (org.daemoxcp.mail.Main.dbManager == null) return null;
        try (java.sql.ResultSet r = org.daemoxcp.mail.Main.dbManager.get_data_config()) {
            return r != null && r.next() ? r.getString(column) : null;
        } catch (Exception e) {
            return null;
        }
    }

    private static void addPort(SortedSet<Integer> ports, String value) {
        if (value == null || !value.trim().matches("[0-9]{1,5}")) return;
        int p = Integer.parseInt(value.trim());
        if (p > 0 && p < 65536) ports.add(p);
    }

    /** Le porte TCP che le regole nel kernel fanno entrare, dall'uscita di pfctl -sr (numeri o nomi). */
    static boolean letsIn(String rules, int port) {
        if (rules == null) return false;
        for (String line : rules.split("\n")) {
            String t = line.trim();
            if (!t.startsWith("pass in") || !t.contains("proto tcp")) continue;
            Matcher m = Pattern.compile("port = (\\S+)").matcher(t);
            while (m.find()) {
                String v = m.group(1);
                if (v.equals(String.valueOf(port)) || (port == 22 && v.equals("ssh"))) return true;
            }
            Matcher set = Pattern.compile("port \\{([^}]*)\\}").matcher(t);
            while (set.find()) {
                for (String v : set.group(1).trim().split("[\\s,]+"))
                    if (v.equals(String.valueOf(port)) || (port == 22 && v.equals("ssh"))) return true;
            }
        }
        return false;
    }

    /**
     * All'avvio della parte root, e quando cambia una porta (la webmail): il pf.conf del pannello con
     * le porte di adesso. Al secondo avvio, se niente e' cambiato, non fa niente.
     */
    public static synchronized void ensureAtBoot() {
        try {
            Path conf = Path.of(PF_CONF);
            if (!Files.isRegularFile(conf) || !Files.isExecutable(Path.of(PFCTL))) return;
            if ("1".equals(Shell.run(Duration.ofSeconds(10), "sysctl", "-n", "security.jail.jailed").outputTrim())) return;
            if (!Shell.run(Duration.ofSeconds(15), PFCTL, "-s", "info").output().contains("Status: Enabled")) return;
            String current = Files.readString(conf, StandardCharsets.UTF_8);
            Ports ports = currentPorts();
            String next = transform(current, ports);
            if (next == null) {
                LOGGER.info("[PfPolicy] /etc/pf.conf has rules the panel does not write: left as it is, every port it lets in stays open");
                return;
            }
            if (next.equals(current)) return;
            apply(conf, current, next, ports);
        } catch (Exception e) {
            LOGGER.warning("[PfPolicy] not applied: " + e.getMessage());
        }
    }

    private static void apply(Path conf, String current, String next, Ports ports) throws Exception {
        Path backup = Path.of(PF_CONF + ".bak." + System.currentTimeMillis());
        Files.copy(conf, backup, StandardCopyOption.COPY_ATTRIBUTES);
        Path tmp = Path.of(PF_CONF + ".panel-new");
        Files.writeString(tmp, next, StandardCharsets.UTF_8);
        Files.setPosixFilePermissions(tmp, PosixFilePermissions.fromString("rw-r--r--"));
        Shell.Result check = Shell.run(Duration.ofSeconds(30), PFCTL, "-nf", tmp.toString());
        if (!check.success()) {
            Files.deleteIfExists(tmp);
            LOGGER.warning("[PfPolicy] the new pf.conf was refused by pfctl, nothing changed: " + check.outputTrim());
            return;
        }
        Files.move(tmp, conf, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        Shell.Result load = Shell.run(Duration.ofSeconds(30), PFCTL, "-f", PF_CONF);
        String rules = Shell.run(Duration.ofSeconds(15), PFCTL, "-sr").output();
        boolean sshOpen = load.success() && ports.ssh().stream().allMatch(p -> letsIn(rules, p));
        if (!sshOpen || !rules.contains("block drop in all")) {
            Files.writeString(conf, current, StandardCharsets.UTF_8);
            Shell.run(Duration.ofSeconds(30), PFCTL, "-f", PF_CONF);
            LOGGER.warning("[PfPolicy] after loading, SSH or the policy did not show in pf's rules: back to the previous pf.conf ("
                    + (load.success() ? "rules checked" : load.outputTrim()) + ")");
            return;
        }
        LOGGER.info("[PfPolicy] DONE: pf lets in only SSH " + list(ports.ssh()) + ", " + list(ports.services())
                + ", essential ICMP, IPv6 neighbours and DHCP replies; the rest is dropped. The previous pf.conf is " + backup);
    }
}
