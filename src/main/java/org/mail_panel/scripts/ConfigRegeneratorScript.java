package org.mail_panel.scripts;

import org.mail_panel.database.MailDatabase;
import java.sql.SQLException;
import java.util.List;

/**
 * Generates script to regenerate Postfix and Dovecot configs
 * from the current database state.
 *
 * Note: Postfix uses MySQL directly for virtual domains/mailboxes/aliases,
 * so this script mainly creates maildir directories and reloads services.
 */
public class ConfigRegeneratorScript {

    private final MailDatabase mailDb;

    public ConfigRegeneratorScript(MailDatabase mailDb) {
        this.mailDb = mailDb;
    }

    public String getScriptContent() {
        StringBuilder script = new StringBuilder();

        script.append("""
            #!/bin/sh
            # Config Regeneration Script
            # Generated by FreeBSD Mail Panel
            #
            # Note: Postfix uses MySQL directly for virtual users.
            # This script creates maildir directories and reloads services.

            """);

        try {
            // Get domains
            List<MailDatabase.Domain> domains = mailDb.getDomains();

            // Create maildir directories
            script.append("# Create maildir directories\n");
            script.append("echo 'Creating maildir directories...'\n");
            for (MailDatabase.Domain domain : domains) {
                script.append("mkdir -p /var/vmail/").append(domain.domain).append("\n");
                List<MailDatabase.Mailbox> mailboxes = mailDb.getMailboxes(domain.id);
                for (MailDatabase.Mailbox mb : mailboxes) {
                    String user = mb.email.split("@")[0];
                    script.append("mkdir -p /var/vmail/").append(domain.domain)
                          .append("/").append(user).append("/Maildir/{cur,new,tmp}\n");
                }
            }
            script.append("chown -R vmail:vmail /var/vmail\n\n");

            // Reload services
            script.append("# Reload services\n");
            script.append("echo 'Reloading Postfix...'\n");
            script.append("service postfix reload 2>/dev/null || true\n");
            // Si chiede a Dovecot se accetta la configurazione PRIMA di ricaricarla.
            // Un reload su una configurazione rotta ferma il servizio: meglio non ricaricare
            // e lasciare in servizio quella precedente, dicendolo a chiare lettere.
            script.append("echo 'Checking the Dovecot configuration...'\n");
            script.append("if command -v doveconf >/dev/null 2>&1; then\n");
            script.append("    DOVECONF_ERR=$(doveconf -n 2>&1 >/dev/null)\n");
            script.append("    if [ -n \"$DOVECONF_ERR\" ]; then\n");
            script.append("        echo '[ERROR] Dovecot does not accept the configuration: NOT reloading it.'\n");
            script.append("        echo \"$DOVECONF_ERR\" | sed 's/^/         /'\n");
            script.append("        echo '[INFO] The service keeps running with the previous configuration.'\n");
            script.append("    else\n");
            script.append("        echo 'Reloading Dovecot...'\n");
            script.append("        service dovecot reload 2>/dev/null || true\n");
            script.append("    fi\n");
            script.append("else\n");
            script.append("    echo 'Reloading Dovecot (doveconf not available, no check possible)...'\n");
            script.append("    service dovecot reload 2>/dev/null || true\n");
            script.append("fi\n");
            script.append("\n");
            script.append("echo 'Configuration regenerated successfully'\n");

        } catch (SQLException e) {
            script.append("echo 'Error: ").append(e.getMessage()).append("'\n");
            script.append("exit 1\n");
        }

        return script.toString();
    }
}
