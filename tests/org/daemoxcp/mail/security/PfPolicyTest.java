package org.daemoxcp.mail.security;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

/**
 * pf lets in only what is needed (PfPolicy).
 *
 *  1. the panel's pf.conf files of before (the real server's, the installer's, the page button's) become
 *     the new one: the fail2ban anchor, the permaban table and the panel's anchor stay, the table limit
 *     stays, the "pass everything" goes, and in comes only SSH (sshd's ports and 22), mail, web, webmail
 *     and the panel, plus ICMP, ICMPv6 and DHCP replies;
 *  2. a pf.conf with rules the panel does not write is left alone, and so is one with another first line;
 *  3. a second time nothing changes; a new webmail port or a second sshd port is followed;
 *  4. the outputs it reads: sockstat (sshd's ports) and pfctl -sr (is SSH let in);
 *  5. on the VM, as root (-De2e.vm=yes): the real pfctl accepts the file it writes (syntax only, nothing loaded);
 *  6. the provider's metadata service (169.254.169.254) only for root: the rule is in the file once, and a panel
 *     pf.conf from before gets it at the next start (MetadataRootOnlyTest checks the live pf on the VM).
 *
 * Usage (on the VM):
 *   java -De2e.vm=yes -cp "tests:target/daemoxcp-mail.jar" org.daemoxcp.mail.security.PfPolicyTest
 */
public class PfPolicyTest {

    static int failed = 0;

    static void check(String what, boolean ok) {
        System.out.println((ok ? "  OK     " : "  FAILED ") + what);
        if (!ok) failed++;
    }

    /** The real server's pf.conf on 08/11/2026 (PfFirewallManager and Fail2banAutoSetup added to it). */
    static final String SERVER = """
            # /etc/pf.conf — generato automaticamente dal mail panel
            # Configurazione MINIMA e SICURA per Fail2ban+pf
            # - Nessun servizio è bloccato (no rischio lockout)

            # Loopback non filtrato
            # Panel firewall: aumenta limit tabelle per geo CIDR
            set limit table-entries 2000000

            set skip on lo

            anchor "f2b/*"

            # Default: pass tutto (niente blocco a parte gli anchor sopra)
            pass

            # === Permaban (auto-gestito dal mail panel) ===
            table <permaban> persist file "/var/db/daemoxcp-mail/permaban.list"
            block in quick from <permaban>

            # Panel firewall anchor (auto-aggiunto)
            anchor "panel-fw"
            # (rimosso da panel) load anchor "panel-fw" from "/etc/pf.anchors/panel-fw.conf"
            """;

    /** The VM's, written by the installer. */
    static final String INSTALLER = """
            # /etc/pf.conf, scritto dall'installazione del pannello mail.
            #
            # Configurazione MINIMA e SICURA per fail2ban + pf:

            # Il loopback non si filtra.
            set skip on lo

            table <permaban> persist file "/var/db/daemoxcp-mail/permaban.list"
            block in quick from <permaban>

            anchor "f2b/*"

            # Predefinito: passa tutto. Niente e' bloccato a parte quanto sopra.
            pass
            """;

    static final String BUTTON = """
            # /etc/pf.conf, generated by the mail panel
            # MINIMAL and SAFE configuration for Fail2ban + pf

            set skip on lo
            anchor "f2b/*"
            pass
            """;

    static PfPolicy.Ports ports(Set<Integer> ssh, Integer... services) {
        return new PfPolicy.Ports(new TreeSet<>(ssh), new TreeSet<>(List.of(services)));
    }

    static List<String> rules(String conf) {
        return conf.lines().map(String::trim).filter(l -> !l.isEmpty() && !l.startsWith("#")).toList();
    }

    public static void main(String[] args) throws Exception {
        PfPolicy.Ports today = ports(Set.of(22), 2096, 8443);

        System.out.println("== 1. The panel's pf.conf files become the new one ==");
        String fromServer = PfPolicy.transform(SERVER, today);

        // IPv4, IPv6 or both (IpFamily): only the services rule takes the family; SSH never does.
        String v6only = PfPolicy.transform(SERVER, today, "inet6 ");
        check("IPv6 only: the services rule is \"pass in inet6 proto tcp\", SSH's has no family",
                v6only != null && v6only.contains("\npass in inet6 proto tcp to port { 25,") && v6only.contains("\npass in proto tcp to port { 22 } keep state\n"));
        String back = PfPolicy.transform(v6only, today, "inet ");
        check("  and a pf.conf with the family is still the panel's: it becomes IPv4 only, then both again",
                back != null && back.contains("\npass in inet proto tcp to port { 25,") && fromServer != null
                        && fromServer.equals(PfPolicy.transform(back, today, "")) && fromServer.equals(PfPolicy.transform(back, today)));
        check("the real server's file is the panel's and is transformed", fromServer != null && fromServer.startsWith(PfPolicy.HEADER));
        // The panel's own file with the first line it had before the product name (DaemoxCP Mail, 17/11/2026):
        // only that line changes, the rules stay exactly the same.
        String previous = fromServer == null ? null : fromServer.replace(PfPolicy.HEADER, PfPolicy.PREVIOUS_HEADER);
        check("the panel's file with the header of before the product name: only the first line changes",
                previous != null && !previous.equals(fromServer) && fromServer.equals(PfPolicy.transform(previous, today))
                        && PfPolicy.HEADER.contains(org.daemoxcp.mail.system.Product.NAME));
        check("  and the installer's header of today is recognised as the panel's",
                PfPolicy.OLD_HEADERS.contains("# /etc/pf.conf, scritto dall'installazione di DaemoxCP Mail.")
                        && PfPolicy.transform(INSTALLER.replace("scritto dall'installazione del pannello mail.",
                                "scritto dall'installazione di DaemoxCP Mail."), today) != null);
        List<String> r = fromServer == null ? List.of() : rules(fromServer);
        check("  the table limit stays", r.contains("set limit table-entries 2000000"));
        check("  the fail2ban anchor, the permaban table and the panel's anchor stay", r.contains("anchor \"f2b/*\"")
                && r.contains("table <permaban> persist file \"/var/db/daemoxcp-mail/permaban.list\"") && r.contains("block in quick from <permaban>")
                && r.contains("anchor \"panel-fw\""));
        check("  the blocks come before the default, which is: nothing comes in", r.indexOf("anchor \"panel-fw\"") < r.indexOf("block in all")
                && r.indexOf("anchor \"f2b/*\"") < r.indexOf("block in all"));
        check("  the 'pass everything' is gone", !r.contains("pass"));
        check("  everything goes out", r.contains("pass out all keep state"));
        check("  SSH comes in, as before: port 22, from anywhere", r.contains("pass in proto tcp to port { 22 } keep state"));
        check("  mail, web, webmail and panel come in", r.contains("pass in proto tcp to port { 25, 80, 143, 443, 465, 587, 993, 2096, 8443 } keep state"));
        check("  POP3, ManageSieve and the rest do not", r.stream().noneMatch(l -> l.matches(".*\\b(110|995|4190|3306)\\b.*")));
        check("  ICMP, ICMPv6 and DHCP replies come in (without them the machine loses the network)",
                r.contains("pass in inet proto icmp icmp-type { echoreq, unreach, timex, paramprob }")
                && r.contains("pass in inet6 proto icmp6") && r.contains("pass in inet proto udp from port 67 to port 68"));
        String fromInstaller = PfPolicy.transform(INSTALLER, today);
        check("the installer's file is transformed, without a table limit it did not have",
                fromInstaller != null && rules(fromInstaller).stream().noneMatch(l -> l.startsWith("set limit")));
        check("the page button's file is transformed", PfPolicy.transform(BUTTON, today) != null);

        System.out.println("\n== 2. What is not the panel's stays as it is ==");
        check("a panel file with a rule of someone else: left alone",
                PfPolicy.transform(SERVER + "pass in proto tcp to port 3306\n", today) == null);
        check("a file with another first line: left alone",
                PfPolicy.transform("# my firewall\nset skip on lo\npass\n", today) == null);
        check("the new file with a rule added by hand: left alone",
                PfPolicy.transform(fromServer + "pass in proto udp to port 51820\n", today) == null);
        check("no file: nothing", PfPolicy.transform(null, today) == null);

        System.out.println("\n== 3. A second time, and when a port changes ==");
        check("a second time the same file", fromServer != null && fromServer.equals(PfPolicy.transform(fromServer, today)));
        String moved = PfPolicy.transform(fromServer, ports(Set.of(22), 2096, 9443));
        check("a new webmail port is followed (9443 in, 8443 out)", moved != null && moved.contains("9443") && !moved.contains("8443"));
        String twoSsh = PfPolicy.transform(fromServer, ports(Set.of(2222), 2096, 8443));
        check("sshd on 2222 too: SSH lets in 22 and 2222, and the services line does not repeat them", twoSsh != null
                && twoSsh.contains("pass in proto tcp to port { 22, 2222 } keep state")
                && twoSsh.contains("pass in proto tcp to port { 25, 80, 143, 443, 465, 587, 993, 2096, 8443 } keep state"));

        System.out.println("\n== 4. What it reads ==");
        String sockstat = """
                USER     COMMAND    PID   FD  PROTO  LOCAL ADDRESS         FOREIGN ADDRESS
                root     sshd       812   4   tcp6   *:22                  *:*
                root     sshd       812   5   tcp4   *:22                  *:*
                root     sshd       812   6   tcp4   *:2222                *:*
                root     dovecot    901   20  tcp4   *:993                 *:*
                """;
        check("sshd's ports from sockstat: 22 and 2222 (" + PfPolicy.sshPorts(sockstat) + ")",
                PfPolicy.sshPorts(sockstat).equals(new TreeSet<>(Set.of(22, 2222))));
        String pfctl = """
                anchor "f2b/*" all
                block drop in quick from <permaban> to any
                anchor "panel-fw" all
                block drop in all
                pass out all flags S/SA keep state
                pass in proto tcp from any to any port = ssh flags S/SA keep state
                pass in proto tcp from any to any port = 2222 flags S/SA keep state
                pass in proto tcp from any to any port = smtp flags S/SA keep state
                """;
        check("pfctl -sr: SSH on 22 (as 'ssh') and on 2222 is let in", PfPolicy.letsIn(pfctl, 22) && PfPolicy.letsIn(pfctl, 2222));
        check("  and 4190 is not", !PfPolicy.letsIn(pfctl, 4190));

        System.out.println("\n== 6. The provider's metadata service only for root ==");
        check("the rule: TCP and UDP to 169.254.169.254 refused at once for every user but root",
                r.contains("block return out quick proto { tcp, udp } to 169.254.169.254 user != 0"));
        check("  once, outgoing only, and nothing else names that address", r.stream().filter(l -> l.contains("169.254.169.254")).count() == 1
                && r.stream().filter(l -> l.contains("169.254.169.254")).allMatch(l -> l.startsWith("block return out quick")));
        check("  in the IPv6-only file too (the family touches only the services rule)",
                v6only != null && v6only.contains("\n" + PfPolicy.METADATA_RULE + "\n"));
        String withoutRule = fromServer == null ? "" : java.util.Arrays.stream(fromServer.split("\n", -1))
                .filter(l -> !l.contains("169.254.169.254") && !l.contains("metadati") && !l.contains("e' nato"))
                .collect(java.util.stream.Collectors.joining("\n"));
        check("a panel pf.conf from before the rule is still the panel's, and at the next start it gets the rule",
                !withoutRule.contains("169.254.169.254") && fromServer != null && fromServer.equals(PfPolicy.transform(withoutRule, today)));

        boolean e2e = "yes".equals(System.getProperty("e2e.vm")) && "root".equals(System.getProperty("user.name"));
        if (e2e) {
            System.out.println("\n== 5. The real pfctl ==");
            Path f = Files.createTempFile("pf-policy-", ".conf");
            Files.writeString(f, fromServer);
            org.daemoxcp.mail.util.Shell.Result syntax = org.daemoxcp.mail.util.Shell.run("/sbin/pfctl", "-nf", f.toString());
            check("pfctl -nf accepts the file (" + syntax.outputTrim() + ")", syntax.success());
            Files.deleteIfExists(f);
        } else {
            System.out.println("\n  (part 5 skipped: it needs pfctl as root, turned on with -De2e.vm=yes on the VM)");
        }

        System.out.println(failed == 0 ? "\nALL OK" : "\n" + failed + " CHECKS FAILED");
        System.exit(failed == 0 ? 0 : 1);
    }
}
