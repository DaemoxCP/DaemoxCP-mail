package org.daemoxcp.mail.system;

/**
 * POP3 on or off (Pop3): the protocols line of dovecot.conf with or without pop3, and nothing else.
 *
 *  1. off: the line the panel wrote loses pop3 and keeps the rest, the rest of the file is the same;
 *  2. on: pop3 comes back right after imap; a second time nothing changes;
 *  3. nothing to do: already as asked, no protocols line, two protocols lines (not the panel's file),
 *     pop3 alone (off would leave no protocol), a word that only contains pop3;
 *  4. sockstat: which ports listen.
 * The real switch runs at the panel's start and from Settings; on the VM it is tried through the panel
 * (ports 110 and 995 open and closed, also from outside).
 *
 * Usage: java -cp "tests:target/daemoxcp-mail-1.0.jar" org.daemoxcp.mail.system.Pop3Test
 */
public class Pop3Test {

    static int failed = 0;

    static void check(String what, boolean ok) {
        System.out.println((ok ? "  OK     " : "  FAILED ") + what);
        if (!ok) failed++;
    }

    public static void main(String[] args) {
        System.out.println("== 1. Off ==");
        String conf = "# Dovecot — generated by FreeBSD Mail Panel\nprotocols = imap pop3 lmtp sieve\nlisten = *, ::\n!include conf.d/*.conf\n";
        String off = Pop3.withPop3(conf, false);
        check("pop3 goes, imap lmtp sieve stay", off != null && off.contains("\nprotocols = imap lmtp sieve\n"));
        check("  the rest of the file is the same", off != null && off.replace("protocols = imap lmtp sieve", "protocols = imap pop3 lmtp sieve").equals(conf));
        check("  a second time: nothing to do", Pop3.withPop3(off, false) == null);
        check("'protocols=pop3 imap' becomes 'protocols=imap'", "protocols=imap\n".equals(Pop3.withPop3("protocols=pop3 imap\n", false)));

        System.out.println("\n== 2. On ==");
        String on = Pop3.withPop3(off, true);
        check("pop3 comes back right after imap: the panel's line again", conf.equals(on));
        check("  a second time: nothing to do", Pop3.withPop3(on, true) == null);
        check("without imap it goes at the end", "protocols = lmtp pop3\n".equals(Pop3.withPop3("protocols = lmtp\n", true)));

        System.out.println("\n== 3. Nothing to do ==");
        check("off, and there is no pop3", Pop3.withPop3("protocols = imap lmtp\n", false) == null);
        check("no protocols line", Pop3.withPop3("listen = *\n", false) == null && Pop3.withPop3("listen = *\n", true) == null);
        check("two protocols lines: not the panel's file", Pop3.withPop3("protocols = imap pop3\nprotocols = imap pop3 lmtp\n", false) == null);
        check("pop3 alone: off would leave no protocol", Pop3.withPop3("protocols = pop3\n", false) == null);
        check("a word that only contains pop3 is not pop3", Pop3.withPop3("protocols = imap pop3s\n", false) == null);

        System.out.println("\n== 4. sockstat ==");
        String s = """
                USER     COMMAND    PID   FD  PROTO  LOCAL ADDRESS         FOREIGN ADDRESS
                root     dovecot    901   20  tcp4   *:993                 *:*
                root     dovecot    901   21  tcp4   *:110                 *:*
                root     sshd       812   4   tcp6   *:22                  *:*
                """;
        check("993 and 110 listen, 995 does not", Pop3.listens(s, 993) && Pop3.listens(s, 110) && !Pop3.listens(s, 995));
        check("2110 is not 110", !Pop3.listens("root x 1 1 tcp4 *:2110 *:*", 110));

        System.out.println(failed == 0 ? "\nALL OK" : "\n" + failed + " CHECKS FAILED");
        System.exit(failed == 0 ? 0 : 1);
    }
}
