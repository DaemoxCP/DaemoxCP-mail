package org.daemoxcp.mail.system;

import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;

import org.daemoxcp.mail.security.DkimManager;
import org.daemoxcp.mail.util.Shell;

/**
 * Rspamd signs only the domains that have their own DKIM key (DkimFallback): try_fallback = false in
 * local.d/dkim_signing.conf. Measured on the real server on 21/11/2026: every night at 03:01 and 04:15 root's periodic
 * reports (the machine's own name, not a mail domain) made Rspamd log «cannot load dkim key /var/db/rspamd/dkim/...:
 * cannot stat key file»; on the VM installed from the README the file did not exist at all, and every local or
 * signed-in message of a domain without a key did the same.
 *  1. the decision: missing file written, the panel's file (DkimManager's or RspamdScript's header) gets the line,
 *     try_fallback already there (any value) or a file written by hand: as it is; only the panel's Rspamd (milter);
 *  2. the line goes right after allow_username_mismatch and the rest stays byte for byte;
 *  3. rspamadm configdump read as «try_fallback = false»;
 *  4. DkimManager and the Rspamd installer write the line, and the panel's start runs the repair after HeaderFromCheck;
 *  5. with -De2e.vm=yes, as root on the VM after the repair: configdump says false; a signed-in message of a domain
 *     without a key adds no «cannot load dkim key» line to Rspamd's log; a domain given a key for the test (a block
 *     added for a moment, then the file put back) is still signed (DKIM_SIGNED).
 *   java [-De2e.vm=yes] -cp "tests:target/daemoxcp-mail.jar" org.daemoxcp.mail.system.DkimFallbackTest
 */
public class DkimFallbackTest {

    static int failed = 0;

    static void check(String what, boolean ok) {
        System.out.println((ok ? "  OK     " : "  FAILED ") + what);
        if (!ok) failed++;
    }

    /** The panel's file as the real server had it on 21/11/2026, with the domains replaced. */
    static final String PANEL_FILE = "# DKIM Signing Configuration\n# Auto-generated by DaemoxCP Mail\n# DO NOT EDIT MANUALLY\n\n"
            + "allow_username_mismatch = true;\n\ndomain {\n    example.org {\n        path = \"/usr/local/etc/mail/dkim/example.org.r20260902.key\";\n"
            + "        selector = \"r20260902\";\n    }\n}\n";
    static final String SCRIPT_FILE = "# DKIM Signing\n# Keys are generated per-domain by the panel\n\nallow_username_mismatch = true;\n\n"
            + "domain {\n    # Domains will be added here by the panel\n}\n";
    static final String PROXY = "milter = yes;\ntimeout = 120s;\n";

    public static void main(String[] a) throws Exception {
        System.out.println("== 1. The decision");
        check("Rspamd not installed: nothing", DkimFallback.decide(false, PROXY, null) == DkimFallback.Action.NOTHING);
        check("not the panel's Rspamd (no milter proxy): nothing", DkimFallback.decide(true, null, null) == DkimFallback.Action.NOTHING
                && DkimFallback.decide(true, "timeout = 120s;\n", null) == DkimFallback.Action.NOTHING);
        check("no dkim_signing.conf (the VM from the README): written", DkimFallback.decide(true, PROXY, null) == DkimFallback.Action.WRITE);
        check("the panel's file without the line (the real server): the line added", DkimFallback.decide(true, PROXY, PANEL_FILE) == DkimFallback.Action.INSERT);
        check("the installer's file: the line added", DkimFallback.decide(true, PROXY, SCRIPT_FILE) == DkimFallback.Action.INSERT);
        check("already false: nothing", DkimFallback.decide(true, PROXY, DkimFallback.inserted(PANEL_FILE)) == DkimFallback.Action.NOTHING);
        check("try_fallback = true set by someone: as it is", DkimFallback.decide(true, PROXY,
                PANEL_FILE.replace("allow_username_mismatch = true;\n", "allow_username_mismatch = true;\ntry_fallback = true;\n")) == DkimFallback.Action.NOTHING);
        check("written by hand: as it is", DkimFallback.decide(true, PROXY, "domain { x.org { path = \"/k\"; } }\n") == DkimFallback.Action.LEFT_ALONE);
        check("the panel's header but no allow_username_mismatch line: as it is", DkimFallback.decide(true, PROXY,
                PANEL_FILE.replace("allow_username_mismatch = true;\n", "")) == DkimFallback.Action.LEFT_ALONE);

        System.out.println("\n== 2. The line");
        String after = DkimFallback.inserted(PANEL_FILE);
        check("right after allow_username_mismatch", after.contains("\nallow_username_mismatch = true;\n" + DkimManager.NO_FALLBACK + "\n\ndomain {\n"));
        check("the rest byte for byte", after.replace(DkimManager.NO_FALLBACK + "\n", "").equals(PANEL_FILE));
        check("the installer's file too", DkimFallback.inserted(SCRIPT_FILE).replace(DkimManager.NO_FALLBACK + "\n", "").equals(SCRIPT_FILE));
        check("the line is the right one", DkimManager.NO_FALLBACK.equals("try_fallback = false;"));

        System.out.println("\n== 3. rspamadm configdump");
        check("try_fallback = false; read as done", DkimFallback.dumpSaysNoFallback("*** Section dkim_signing ***\nselector = \"dkim\";\ntry_fallback = false;\n"));
        check("try_fallback = true; (the default) read as not done", !DkimFallback.dumpSaysNoFallback("try_fallback = true;\nuse_domain = \"header\";\n"));
        check("no answer: not done", !DkimFallback.dumpSaysNoFallback(null) && !DkimFallback.dumpSaysNoFallback(""));

        System.out.println("\n== 4. Where it is written");
        String manager = Files.readString(Path.of("src/main/java/org/daemoxcp/mail/security/DkimManager.java"));
        int text = manager.indexOf("public String rspamdConfigText()");
        check("DkimManager writes the line after allow_username_mismatch", text > 0
                && manager.indexOf("config.append(\"allow_username_mismatch = true;\\n\");\n        config.append(NO_FALLBACK)", text) > text);
        check("  and updateRspamdConfig writes that text, readable by rspamd (0644)", manager.contains("String config = rspamdConfigText();")
                && manager.contains("Files.setPosixFilePermissions(configPath, java.nio.file.attribute.PosixFilePermissions.fromString(\"rw-r--r--\"))"));
        check("the header DkimFallback knows", (PANEL_FILE).startsWith(DkimManager.CONFIG_HEADER) && manager.contains("\"# Auto-generated by DaemoxCP Mail\\n\""));
        String script = new org.daemoxcp.mail.scripts.RspamdScript().getScriptContent();
        check("the Rspamd installer writes the line", script.contains("\nallow_username_mismatch = true;\ntry_fallback = false;\n")
                && script.contains(DkimFallback.SCRIPT_HEADER));
        String server = Files.readString(Path.of("src/main/java/org/daemoxcp/mail/webserver/SSLMailServer.java"));
        int from = server.indexOf("HeaderFromCheck.ensureAtBoot();"), fallback = server.indexOf("DkimFallback.ensureAtBoot();");
        check("the panel's start runs the repair after HeaderFromCheck", from > 0 && fallback > from);

        if (!"yes".equals(System.getProperty("e2e.vm"))) {
            System.out.println("\n  (part 5 skipped: it asks Rspamd on the TEST VM, turned on with -De2e.vm=yes)");
        } else {
            live();
        }

        System.out.println(failed == 0 ? "\nALL OK" : "\n" + failed + " CHECKS FAILED");
        System.exit(failed == 0 ? 0 : 1);
    }

    // ===================== 5. On the VM =====================

    static final String LOG = "/var/log/rspamd/rspamd.log";

    static void live() throws Exception {
        System.out.println("\n== 5. Live, on the VM");
        String dump = sh(RspamdController.RSPAMADM + " configdump dkim_signing");
        check("configdump: try_fallback = false", DkimFallback.dumpSaysNoFallback(dump));
        long before = errors();
        String nokey = scan("probe@nokey-" + System.nanoTime() + ".invalid");
        Thread.sleep(2000);
        check("a signed-in message of a domain without a key: scanned, not signed (" + nokey.lines().filter(l -> l.startsWith("Action")).findFirst().orElse("no answer") + ")",
                nokey.contains("Action:") && !nokey.contains("DKIM_SIGNED"));
        check("  and no «cannot load dkim key» in Rspamd's log (" + before + " -> " + errors() + ")", errors() == before);

        // A domain with a key, for a moment: the file with one more block, then put back.
        Path file = DkimFallback.FILE, key = Path.of("/var/tmp/dkim-fallback-test.key");
        byte[] original = Files.exists(file) ? Files.readAllBytes(file) : null;
        try {
            sh(RspamdController.RSPAMADM + " dkim_keygen -b 1024 -s fbtest -d dkimtest.invalid -k " + key + " >/dev/null && chown rspamd " + key + " && chmod 600 " + key);
            String block = "    dkimtest.invalid {\n        path = \"" + key + "\";\n        selector = \"fbtest\";\n    }\n";
            String withKey = original == null ? DkimManager.NO_FALLBACK + "\ndomain {\n" + block + "}\n"
                    : new String(original).replace("domain {\n", "domain {\n" + block);
            Files.writeString(file, withKey);
            sh("service rspamd reload >/dev/null 2>&1");
            String signed = "";
            for (int i = 0; i < 20 && !signed.contains("DKIM_SIGNED"); i++) {
                Thread.sleep(1000);
                signed = scan("probe@dkimtest.invalid");
            }
            check("a domain with its key: still signed (DKIM_SIGNED)", signed.contains("DKIM_SIGNED"));
        } finally {
            if (original == null) Files.deleteIfExists(file);
            else Files.write(file, original);
            Files.deleteIfExists(key);
            sh("service rspamd reload >/dev/null 2>&1");
            Thread.sleep(2000);
            check("the file put back as it was", original == null ? !Files.exists(file) : java.util.Arrays.equals(Files.readAllBytes(file), original));
        }
    }

    /** rspamc as a client signed in with that address, From the same address. */
    static String scan(String address) {
        String message = "From: <" + address + ">\r\nTo: <other@daemoxcp-mail.invalid>\r\nSubject: dkim fallback probe\r\n"
                + "Message-ID: <dkim-fallback-" + System.nanoTime() + "@daemoxcp-mail.invalid>\r\nContent-Type: text/plain\r\n\r\nprobe\r\n";
        return Shell.runWithInput(Duration.ofSeconds(60), message, RspamdUser.RSPAMC, "-h", "127.0.0.1:11333", "--user", address,
                "--from", address, "--rcpt", "other@daemoxcp-mail.invalid", "--ip", "127.0.0.1", "symbols").output();
    }

    static long errors() {
        return sh("grep -c 'cannot load dkim key' " + LOG).lines().findFirst().map(String::trim)
                .filter(x -> x.matches("\\d+")).map(Long::parseLong).orElse(0L);
    }

    static String sh(String command) {
        return Shell.run(Duration.ofSeconds(90), "sh", "-c", command).output();
    }
}
