package org.mail_panel.security;

/**
 * The surgical edit of jail.local.
 *
 * It must be tested because it writes to a live configuration file that decides who gets blocked,
 * and because its errors do not show: a line inserted in the wrong section, or a tail of an action
 * left attached, produce a file fail2ban may even accept while it bans with another jail's
 * command. Here it is checked not only that the right line changes, but that all the rest of the
 * file stays identical.
 *
 * The panel's messages are read in English (I18n.setCurrent): outside a request it writes Italian.
 */
public class BanActionRepairTest {

    private static int failed = 0;

    private static final String REAL =
        "# Auto-generated by FreeBSD-Mail-Panel\n" +
        "[mail-panel-auth]\n" +
        "enabled  = true\n" +
        "filter   = mail-panel-auth\n" +
        "logpath  = /var/log/mail-panel-auth.log\n" +
        "maxretry = 5\n" +
        "findtime = 600\n" +
        "bantime  = 3600\n" +
        "backend  = auto\n";

    public static void main(String[] args) {
        org.mail_panel.i18n.I18n.setCurrent("en");
        // --- The real case: a section without an action, as on the server ---
        BanActionRepair.Outcome e = BanActionRepair.withPfAction(REAL, "mail-panel-auth");
        real("section without an action: modified", e.type == BanActionRepair.Outcome.Kind.MODIFIED);
        real("pf action inserted", e.content.contains("action   = pf[name=mail-panel-auth, port=\"0:65535\"]"));
        // "pf" being there is not enough: without a port the action uses the default "any port
        // $port", and with the port empty pf refuses the rule leaving the table without anybody
        // reading it — it is what happened to recidive. The port is declared.
        //
        // The first fix used "actiontype", which is the form shown by the action's documentation:
        // on this system fail2ban does not accept it as a jail parameter and loads the jail WITHOUT
        // any action ("No actions for jail ..."), that is without banning at all. Here the form
        // declared with the port is tested, the one with which the four mail jails have their
        // table and rule verified.
        real("port declared, not left to the default",
            !e.content.contains("pf[name=mail-panel-auth]"));
        real("no actiontype: fail2ban refuses it here",
            !e.content.contains("actiontype"));
        // It goes after the last configuration line, not at the end of the file after the newline.
        same("inserted in the right place",
            "backend  = auto\naction   = pf[name=mail-panel-auth, port=\"0:65535\"]\n",
            e.content.substring(e.content.indexOf("backend  = auto")));
        // Nothing else changed.
        same("the rest of the file is untouched", REAL.replace("backend  = auto\n", ""),
            e.content.replace("backend  = auto\n", "").replace("action   = pf[name=mail-panel-auth, port=\"0:65535\"]\n", ""));

        // --- Applying it twice must not add two ---
        BanActionRepair.Outcome again = BanActionRepair.withPfAction(e.content, "mail-panel-auth");
        real("second pass: already in place", again.type == BanActionRepair.Outcome.Kind.ALREADY_IN_PLACE);

        // --- An iptables action is replaced, not put alongside ---
        String ipt = REAL + "action   = iptables-multiport[name=x, port=\"http\"]\n";
        BanActionRepair.Outcome s = BanActionRepair.withPfAction(ipt, "mail-panel-auth");
        real("iptables: replaced", s.type == BanActionRepair.Outcome.Kind.MODIFIED);
        real("iptables: gone", !s.content.contains("iptables"));
        same("a single action", 1, count(s.content, "action   = pf"));

        // banaction is the other name of the same thing and is treated the same way.
        BanActionRepair.Outcome ba = BanActionRepair.withPfAction(
            REAL + "banaction = iptables-allports\n", "mail-panel-auth");
        real("banaction: replaced", ba.type == BanActionRepair.Outcome.Kind.MODIFIED);
        real("banaction: iptables gone", !ba.content.contains("iptables"));

        // --- An unresolved placeholder is not "already in place" ---
        // It is the form that made the panel's two jails stop reporting their own action: it starts
        // with "pf[", so a naive check promotes it and leaves it there.
        BanActionRepair.Outcome ph = BanActionRepair.withPfAction(
            REAL + "action   = pf[name=mail-panel-auth, actiontype=<allports>]\n", "mail-panel-auth");
        real("placeholder in the value: to be rewritten",
            ph.type == BanActionRepair.Outcome.Kind.MODIFIED);
        real("placeholder replaced with the literal value",
            ph.content.contains("port=\"0:65535\"") && !ph.content.contains("<allports>"));
        // But the form already correct is not touched: rewriting it at every pass would reload
        // fail2ban for no reason, and a remedy that always acts cannot be told from a defect.
        real("correct form left alone",
            BanActionRepair.withPfAction(REAL + "action   = pf[name=mail-panel-auth, port=\"0:65535\"]\n",
                "mail-panel-auth").type == BanActionRepair.Outcome.Kind.ALREADY_IN_PLACE);

        // --- The form fail2ban refuses is rewritten, not promoted ---
        // "pf[name=x, actiontype=any]" starts with "pf[" and contains no placeholder: a check that
        // settles for that leaves it, and the jail stays without actions. It really happened, twice
        // in a row with two variants. The condition is the port.
        BanActionRepair.Outcome at = BanActionRepair.withPfAction(
            REAL + "action   = pf[name=mail-panel-auth, actiontype=any]\n", "mail-panel-auth");
        real("actiontype without a port: to be rewritten",
            at.type == BanActionRepair.Outcome.Kind.MODIFIED);
        real("rewritten with the port and without actiontype",
            at.content.contains("port=\"0:65535\"") && !at.content.contains("actiontype"));
        // A port chosen by whoever administers is NOT touched: it is a configuration, not a fault.
        real("custom port respected",
            BanActionRepair.withPfAction(REAL + "action   = pf[name=mail-panel-auth, port=\"smtp,imaps\"]\n",
                "mail-panel-auth").type == BanActionRepair.Outcome.Kind.ALREADY_IN_PLACE);

        // --- The case that must NOT be repaired ---
        String multi = REAL + "action   = iptables-multiport[name=x]\n         sendmail[dest=root]\n";
        BanActionRepair.Outcome m = BanActionRepair.withPfAction(multi, "mail-panel-auth");
        real("action on more lines: it stops", m.type == BanActionRepair.Outcome.Kind.TO_REVIEW);
        real("action on more lines: no content written", m.content == null);
        real("action on more lines: it says where to look", m.reason != null && m.reason.contains("line"));

        // --- Missing section: nothing is made up ---
        real("missing section",
            BanActionRepair.withPfAction("[other]\nenabled = true\n", "mail-panel-auth").type
                == BanActionRepair.Outcome.Kind.ABSENT);

        // --- The worst risk: writing in another jail's section ---
        String second = REAL + "\n[sshd]\nenabled  = true\nmaxretry = 3\n";
        BanActionRepair.Outcome d = BanActionRepair.withPfAction(second, "mail-panel-auth");
        real("two sections: modified", d.type == BanActionRepair.Outcome.Kind.MODIFIED);
        String sshd = d.content.substring(d.content.indexOf("[sshd]"));
        same("the sshd section is untouched", "[sshd]\nenabled  = true\nmaxretry = 3\n", sshd);
        real("the action is BEFORE [sshd]",
            d.content.indexOf("action   = pf") < d.content.indexOf("[sshd]"));

        // A comment at the end of the section must not push the action after it.
        String withNote = "[mail-panel-auth]\nenabled  = true\n# final note\n\n[sshd]\nenabled = true\n";
        BanActionRepair.Outcome cn = BanActionRepair.withPfAction(withNote, "mail-panel-auth");
        real("the action follows the last configuration, not the comment",
            cn.content.indexOf("action   = pf") < cn.content.indexOf("# final note"));

        // --- firstRunnable: it is what tells a real ban from an empty one ---
        same("iptables recognised under the placeholders", "iptables",
            BanActionRepair.firstRunnable("<iptables> -I f2b-x 1 -s <ip> -j <blocktype>"));
        same("pfctl recognised", "pfctl",
            BanActionRepair.firstRunnable("pfctl -a f2b/x -t f2b-x -T add <ip>"));
        same("absolute path", "/sbin/pfctl",
            BanActionRepair.firstRunnable("/sbin/pfctl -t x -T add <ip>"));
        same("empty lines at the top ignored", "pfctl",
            BanActionRepair.firstRunnable("\n   \npfctl -t x -T add <ip>"));

        // The charge "it bans with a command that does not exist" is built on this. A shell
        // construct is not a program to look for on disk: if it concluded "it does not exist", the
        // panel would call a healthy jail broken and invite to repair it.
        same("if is not a program", null,
            BanActionRepair.firstRunnable("if [ -n \"<ip>\" ]; then pfctl -T add <ip>; fi"));
        same("echo is not a program", null,
            BanActionRepair.firstRunnable("echo <ip> >> /var/db/list"));
        same("a variable is not judged", null,
            BanActionRepair.firstRunnable("$BANCMD -s <ip>"));
        same("comments skipped", "pfctl",
            BanActionRepair.firstRunnable("# adds the address\npfctl -t x -T add <ip>"));
        same("missing command", null, BanActionRepair.firstRunnable(null));

        System.out.println(failed == 0 ? "\nALL OK" : "\n" + failed + " CHECKS FAILED");
        if (failed > 0) System.exit(1);
    }

    private static int count(String text, String piece) {
        int n = 0, i = 0;
        while ((i = text.indexOf(piece, i)) >= 0) { n++; i += piece.length(); }
        return n;
    }

    private static void same(String name, Object expected, Object got) {
        boolean ok = expected == null ? got == null : expected.equals(got);
        System.out.println((ok ? "  ok   " : "  NO   ") + name
            + (ok ? "" : "\n         expected [" + expected + "]\n         got      [" + got + "]"));
        if (!ok) failed++;
    }

    private static void real(String name, boolean ok) {
        System.out.println((ok ? "  ok   " : "  NO   ") + name);
        if (!ok) failed++;
    }
}
