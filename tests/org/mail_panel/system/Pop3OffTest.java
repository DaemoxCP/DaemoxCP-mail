package org.mail_panel.system;

/**
 * POP3 off (Pop3Off): the protocols line of dovecot.conf without pop3, and nothing else.
 *
 *  1. the line the panel wrote loses pop3 and keeps the rest, the rest of the file is the same;
 *  2. nothing to do: no pop3, no protocols line, two protocols lines (not the panel's file), pop3 alone;
 *  3. sockstat: which ports listen.
 * The real repair runs at the panel's start; tools/upgrade's passage on the VM checks it (110 and 995 closed,
 * IMAP still answers).
 *
 * Usage: java -cp "tests:target/freebsd-mail-panel-1.0.jar" org.mail_panel.system.Pop3OffTest
 */
public class Pop3OffTest {

    static int failed = 0;

    static void check(String what, boolean ok) {
        System.out.println((ok ? "  OK     " : "  FAILED ") + what);
        if (!ok) failed++;
    }

    public static void main(String[] args) {
        System.out.println("== 1. The panel's line ==");
        String conf = "# Dovecot — generated by FreeBSD Mail Panel\nprotocols = imap pop3 lmtp sieve\nlisten = *, ::\n!include conf.d/*.conf\n";
        String off = Pop3Off.withoutPop3(conf);
        check("pop3 goes, imap lmtp sieve stay (" + (off == null ? null : off.lines().skip(1).findFirst().orElse("")) + ")",
                off != null && off.contains("\nprotocols = imap lmtp sieve\n"));
        check("  the rest of the file is the same", off != null && off.replace("protocols = imap lmtp sieve", "protocols = imap pop3 lmtp sieve").equals(conf));
        check("  a second time: nothing to do", Pop3Off.withoutPop3(off) == null);
        check("spaces and order kept: 'protocols=pop3 imap' becomes 'protocols=imap'",
                "protocols=imap\n".equals(Pop3Off.withoutPop3("protocols=pop3 imap\n")));

        System.out.println("\n== 2. Nothing to do ==");
        check("no pop3", Pop3Off.withoutPop3("protocols = imap lmtp\n") == null);
        check("no protocols line", Pop3Off.withoutPop3("listen = *\n") == null);
        check("two protocols lines: not the panel's file", Pop3Off.withoutPop3("protocols = imap pop3\nprotocols = imap pop3 lmtp\n") == null);
        check("pop3 alone: it would leave no protocol", Pop3Off.withoutPop3("protocols = pop3\n") == null);
        check("a word that only contains pop3 is not pop3", Pop3Off.withoutPop3("protocols = imap pop3s\n") == null);

        System.out.println("\n== 3. sockstat ==");
        String s = """
                USER     COMMAND    PID   FD  PROTO  LOCAL ADDRESS         FOREIGN ADDRESS
                root     dovecot    901   20  tcp4   *:993                 *:*
                root     dovecot    901   21  tcp4   *:110                 *:*
                root     sshd       812   4   tcp6   *:22                  *:*
                """;
        check("993 and 110 listen, 995 does not", Pop3Off.listens(s, 993) && Pop3Off.listens(s, 110) && !Pop3Off.listens(s, 995));
        check("2110 is not 110", !Pop3Off.listens("root x 1 1 tcp4 *:2110 *:*", 110));

        System.out.println(failed == 0 ? "\nALL OK" : "\n" + failed + " CHECKS FAILED");
        System.exit(failed == 0 ? 0 : 1);
    }
}
